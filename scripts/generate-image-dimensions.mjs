import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import imageSize from "image-size";
import sharp from "sharp";
import { rgbaToThumbHash } from "thumbhash";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public");
const outputFile = join(root, "data/imageDimensions.ts");
const scanDirs = ["img/work", "img/life"];
const lifeDir = "img/life";

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      walk(path, files);
      continue;
    }
    if (!/\.(jpe?g|png|webp)$/i.test(name) || /@\d+x\./i.test(name)) continue;
    files.push(path);
  }
  return files;
}

async function generateThumbhash(file) {
  const { data, info } = await sharp(file)
    .ensureAlpha()
    .resize(100, 100, { fit: "inside" })
    .raw()
    .toBuffer({ resolveWithObject: true });

  const hash = rgbaToThumbHash(info.width, info.height, new Uint8Array(data));
  return Buffer.from(hash).toString("base64");
}

function formatEntry(src, { width, height, thumbhash }) {
  if (thumbhash) {
    return `  "${src}": { width: ${width}, height: ${height}, thumbhash: "${thumbhash}" },`;
  }
  return `  "${src}": { width: ${width}, height: ${height} },`;
}

const dimensions = {};

for (const scanDir of scanDirs) {
  const dir = join(publicDir, scanDir);
  if (!statSync(dir, { throwIfNoEntry: false })) continue;

  for (const file of walk(dir)) {
    const src = `/${relative(publicDir, file).replace(/\\/g, "/")}`;
    const { width, height } = imageSize(readFileSync(file));
    if (!width || !height) {
      console.warn(`Skipping ${src}: could not read dimensions`);
      continue;
    }
    dimensions[src] = { width, height };
  }
}

const lifeImagesDir = join(publicDir, lifeDir);
if (statSync(lifeImagesDir, { throwIfNoEntry: false })) {
  for (const file of walk(lifeImagesDir)) {
    const src = `/${relative(publicDir, file).replace(/\\/g, "/")}`;
    if (!dimensions[src]) continue;
    try {
      dimensions[src].thumbhash = await generateThumbhash(file);
    } catch (error) {
      console.warn(`Skipping thumbhash for ${src}:`, error);
    }
  }
}

const sortedEntries = Object.keys(dimensions)
  .sort()
  .map((src) => formatEntry(src, dimensions[src]))
  .join("\n");

const fileContents = `// Generated by scripts/generate-image-dimensions.mjs — do not edit manually
// Regenerate: npm run sync:life

export const imageDimensions = {
${sortedEntries}
} as const;

export type ImageDimensionSrc = keyof typeof imageDimensions;
`;

writeFileSync(outputFile, fileContents);
const lifeCount = Object.values(dimensions).filter((entry) => entry.thumbhash).length;
console.log(`Wrote ${Object.keys(dimensions).length} image entries to data/imageDimensions.ts (${lifeCount} with thumbhash)`);
