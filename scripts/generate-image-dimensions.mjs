import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import imageSize from "image-size";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "public");
const outputFile = join(root, "data/imageDimensions.ts");
const scanDirs = ["img/work", "img/life"];

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      walk(path, files);
      continue;
    }
    if (!/\.(jpe?g|png|webp)$/i.test(name) || /@\d+x\./i.test(name)) continue;
    files.push(path);
  }
  return files;
}

const dimensions = {};

for (const scanDir of scanDirs) {
  const dir = join(publicDir, scanDir);
  if (!statSync(dir, { throwIfNoEntry: false })) continue;

  for (const file of walk(dir)) {
    const src = `/${relative(publicDir, file).replace(/\\/g, "/")}`;
    const { width, height } = imageSize(readFileSync(file));
    if (!width || !height) {
      console.warn(`Skipping ${src}: could not read dimensions`);
      continue;
    }
    dimensions[src] = { width, height };
  }
}

const sortedEntries = Object.keys(dimensions)
  .sort()
  .map((src) => `  "${src}": { width: ${dimensions[src].width}, height: ${dimensions[src].height} },`)
  .join("\n");

const fileContents = `// Generated by scripts/generate-image-dimensions.mjs — do not edit manually
// Regenerate: npm run generate:image-dimensions

export const imageDimensions = {
${sortedEntries}
} as const;

export type ImageDimensionSrc = keyof typeof imageDimensions;
`;

writeFileSync(outputFile, fileContents);
console.log(`Wrote ${Object.keys(dimensions).length} image dimensions to data/imageDimensions.ts`);
